package com.sareemarket.common;

import java.io.FileNotFoundException;
import java.io.InputStream;

import org.springframework.core.io.AbstractResource;
import org.springframework.core.io.ByteArrayResource;
import org.springframework.core.io.Resource;

import software.amazon.awssdk.core.sync.RequestBody;
import software.amazon.awssdk.services.s3.S3Client;
import software.amazon.awssdk.services.s3.model.DeleteObjectRequest;
import software.amazon.awssdk.services.s3.model.GetObjectRequest;
import software.amazon.awssdk.services.s3.model.NoSuchKeyException;
import software.amazon.awssdk.services.s3.model.PutObjectRequest;

/**
 * Photos in an S3 bucket. Collection photos go under {@code prefix} (for example {@code saree-collections/}); payment
 * proofs, whose keys start with {@code proofs/}, go under {@code proofsPrefix}, outside that folder, so opening the photo
 * folder to the public could never expose a customer's payment screenshot. The bucket stays private: the backend reads
 * and writes it with its own credentials and streams photos to the app.
 */
public class S3ImageStorage implements ImageStorage {

	private static final String PROOFS = "proofs/";

	private static final Resource MISSING = new AbstractResource() {
		@Override
		public String getDescription() {
			return "missing S3 object";
		}

		@Override
		public boolean exists() {
			return false;
		}

		@Override
		public InputStream getInputStream() throws FileNotFoundException {
			throw new FileNotFoundException("missing S3 object");
		}
	};

	private final S3Client s3;

	private final String bucket;

	private final String prefix;

	private final String proofsPrefix;

	public S3ImageStorage(S3Client s3, String bucket, String prefix, String proofsPrefix) {
		this.s3 = s3;
		this.bucket = bucket;
		this.prefix = folder(prefix);
		this.proofsPrefix = folder(proofsPrefix);
	}

	@Override
	public void save(String key, byte[] data) {
		s3.putObject(PutObjectRequest.builder().bucket(bucket).key(objectKey(key)).contentType("image/jpeg").build(),
				RequestBody.fromBytes(data));
	}

	@Override
	public Resource load(String key) {
		try {
			byte[] bytes = s3.getObjectAsBytes(GetObjectRequest.builder().bucket(bucket).key(objectKey(key)).build())
				.asByteArray();
			return new ByteArrayResource(bytes);
		}
		catch (NoSuchKeyException e) {
			return MISSING;
		}
	}

	@Override
	public void delete(String key) {
		// S3 deletes a missing key without complaint.
		s3.deleteObject(DeleteObjectRequest.builder().bucket(bucket).key(objectKey(key)).build());
	}

	String objectKey(String key) {
		// Keys are generated by the server, but never trust that: refuse anything that climbs out of its folder.
		if (key.isEmpty() || key.startsWith("/") || key.contains("..") || key.contains("\\")) {
			throw new IllegalArgumentException("Bad storage key: " + key);
		}
		return key.startsWith(PROOFS) ? proofsPrefix + key.substring(PROOFS.length()) : prefix + key;
	}

	private static String folder(String value) {
		String trimmed = value == null ? "" : value.trim();
		return trimmed.isEmpty() || trimmed.endsWith("/") ? trimmed : trimmed + "/";
	}

}
