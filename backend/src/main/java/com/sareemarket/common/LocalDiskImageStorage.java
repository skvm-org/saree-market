package com.sareemarket.common;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;

import org.springframework.core.io.FileSystemResource;
import org.springframework.core.io.Resource;

public class LocalDiskImageStorage implements ImageStorage {

	private final Path root;

	public LocalDiskImageStorage(Path root) {
		this.root = root.toAbsolutePath().normalize();
	}

	@Override
	public void save(String key, byte[] data) {
		Path file = resolve(key);
		try {
			Files.createDirectories(file.getParent());
			Files.write(file, data);
		}
		catch (IOException e) {
			throw new UncheckedIOException("Could not store " + key, e);
		}
	}

	@Override
	public Resource load(String key) {
		return new FileSystemResource(resolve(key));
	}

	@Override
	public void delete(String key) {
		try {
			Files.deleteIfExists(resolve(key));
		}
		catch (IOException e) {
			throw new UncheckedIOException("Could not delete " + key, e);
		}
	}

	// Keys are generated by the server, but never trust that: refuse anything that leaves the root.
	private Path resolve(String key) {
		Path file = root.resolve(key).normalize();
		if (!file.startsWith(root)) {
			throw new IllegalArgumentException("Key escapes the storage root: " + key);
		}
		return file;
	}

}
